"""Constraint-driven resource allocation: pins + DMA (+ already declared peripheral modes).

Input (v2):
- `allocation: {pins: auto|manual, dma: auto|manual, tie_break: stable, release: [...]}`;
- `connections: [{name?, signals: [...], endpoint_pins?: [...]}]`;
- pins/DMA already written in the target are fixed resources and are not moved; only those named in `release` may be reassigned.

Solve: variables = signals to place (or DMA requests), domains = pins the signal can use (channels the request can use); constraints = one signal per pin (same-name shared groups excepted, shared groups are handled elsewhere in iocc) and one request per channel; search = MRV variable choice + forward-checking pruning + backtracking; candidate order follows device pin order / resource name order for determinism. When there is no solution, report a 'minimal explainable conflict set': the unplaced signals, the pins tried, and who occupies them - without claiming it is mathematically minimal.
"""

from __future__ import annotations

from .errors import IocConflict, IocUnsupported


class AllocationError(IocConflict):
    """Allocation has no solution / not enough information. Carries a structured conflict list."""

    def __init__(self, message, where, conflicts):
        super().__init__(message, where)
        self.conflicts = conflicts


def _pin_map(model):
    """Pin name -> set of signals it can carry; also gives the pin order (used as a stable tie-break)."""
    pins = {}
    order = {}
    for index, pin in enumerate(model.device.pins):
        pins[pin.name] = set(pin.signals)
        order[pin.name] = index
    return pins, order


def _release_pins(target, release):
    """Release fixed resources by pin name/signal name from release; return (new pins, released signals)."""
    if not release:
        return list(target.get("pins") or []), set()
    wanted = set(release)
    kept, freed = [], set()
    for item in target.get("pins") or []:
        signal = str(item.get("signal") or "")
        pin = str(item.get("pin") or "")
        if pin in wanted or signal in wanted:
            freed.add(signal)
            continue
        kept.append(item)
    return kept, freed


def _required_signals(target, fixed):
    """Signals to allocate: those in connections + those required by declared modes but not fixed yet."""
    wanted = []
    for connection in target.get("connections") or []:
        for signal in connection.get("signals") or []:
            if signal not in wanted:
                wanted.append(signal)
    for item in target.get("ips") or []:
        if not item.get("mode"):
            continue
        for ref in item.get("modes") or []:
            if ref.get("name") and ref["name"] not in wanted:
                wanted.append(ref["name"])
    return [signal for signal in wanted if signal not in fixed]


def _mode_signals(model, target):
    """Signals required by declared modes (used to add pins when pins are auto)."""
    from . import derive

    wanted = []
    for item in target.get("ips") or []:
        if not item.get("mode"):
            continue
        ip = derive.ip_by_instance(model.ips, item["instance"], model.device.refname)
        try:
            mode = derive.find_mode(ip, item["mode"])
        except IocUnsupported:
            continue
        signal_by_name = ip.signal_by_name()
        for signal in mode.signals or []:
            info = signal_by_name.get(signal)
            if info is not None and getattr(info, "virtual", False):
                # virtual pins never appear on physical pins; they are generated by the encoding layer and are not allocated here.
                continue
            if signal not in wanted:
                wanted.append(signal)
    return wanted


def _candidates(signal, pin_map, endpoint_pins):
    out = [pin for pin, signals in pin_map.items() if signal in signals]
    if endpoint_pins:
        out = [pin for pin in out if pin in endpoint_pins]
    return out


def _endpoint_for_signal(target, signal):
    for connection in target.get("connections") or []:
        if signal in (connection.get("signals") or []):
            return list(connection.get("endpoint_pins") or [])
    return []


def _solve(domains, order):
    """MRV + forward checking + backtracking. Return {signal: pin}."""
    signals = sorted(domains, key=lambda name: (len(domains[name]), name))
    assignment = {}

    def candidates_of(signal, used):
        return [pin for pin in domains[signal] if pin not in used]

    def search(used):
        if len(assignment) == len(signals):
            return True
        remaining = [name for name in signals if name not in assignment]
        # MRV
        best = None
        best_domain = None
        for name in remaining:
            domain = candidates_of(name, used)
            if best is None or len(domain) < len(best_domain):
                best, best_domain = name, domain
                if not domain:
                    break
        if not best_domain:
            return False
        for pin in sorted(best_domain, key=lambda name: order.get(name, 10 ** 9)):
            assignment[best] = pin
            used.add(pin)
            if search(used):
                return True
            used.discard(pin)
            del assignment[best]
        return False

    if not search(set()):
        return None
    return assignment


def _explain(domains, target, fixed_pins):
    """When unsolved, give a readable conflict list: every unplaced signal, its candidates, and who occupies them."""
    holders = {pin: signal for signal, pin in fixed_pins.items()}
    conflicts = []
    for signal in sorted(domains):
        blocked = []
        for pin in domains[signal]:
            if pin in holders:
                blocked.append({"pin": pin, "holder": holders[pin]})
        conflicts.append({"signal": signal, "candidates": list(domains[signal]),
                          "blocked_by": blocked})
    return conflicts


def _dma_candidates(model, target, requests):
    """Request -> candidate streams (mode tree + tristate conditions). All data comes from the db, no hardcoded peripheral map."""
    from . import dmaauto
    from .designstate import DesignState

    state = DesignState(model, target)
    return {request: dmaauto.request_candidates(model, request, state)
            for request in requests}


def allocate(model, target) -> tuple:
    """Return (new target, notes). Only pins and DMA are filled in; everything else is left as is."""
    allocation = target.get("allocation") or {}
    connections = target.get("connections") or []
    mode_pins = allocation.get("pins") == "auto"
    mode_dma = allocation.get("dma") == "auto"
    if not mode_pins and not mode_dma:
        return target, []
    notes = []
    pins, order = _pin_map(model)
    pin_entries, freed = _release_pins(target, allocation.get("release"))
    fixed = {str(item["signal"]): str(item["pin"]) for item in pin_entries if item.get("signal")}
    used_pins = {str(item["pin"]) for item in pin_entries}

    if mode_pins:
        wanted = []
        for connection in connections:
            for signal in connection.get("signals") or []:
                if signal not in fixed and signal not in wanted:
                    wanted.append(signal)
        wanted += [signal for signal in _mode_signals(model, target)
                   if signal not in fixed and signal not in wanted]
        domains = {}
        for signal in wanted:
            candidates = _candidates(signal, pins, _endpoint_for_signal(target, signal))
            candidates = [pin for pin in candidates if pin not in used_pins]
            if not candidates:
                raise AllocationError(
                    "signal %s has no usable pin: either the device does not support it or the candidate pins are taken by fixed resources"
                    % signal, "allocation.pins",
                    [{"signal": signal, "candidates": [], "blocked_by": []}])
            domains[signal] = candidates
        solution = _solve(domains, order)
        if solution is None:
            conflicts = _explain(domains, target, fixed)
            raise AllocationError(
                "these signals cannot be placed together (constraint conflict, see conflicts)",
                "allocation.pins", conflicts)
        solved = len(solution)
        for signal in sorted(solution):
            pin = solution[signal]
            pin_entries.append({"pin": pin, "signal": signal})
            used_pins.add(pin)
        if solved:
            notes.append("auto-allocated %d pins (tie_break=%s)"
                         % (solved, allocation.get("tie_break") or "stable"))

    if mode_dma:
        from . import dmaauto

        dma_entries = list(target.get("dma") or [])
        wanted = [entry for entry in dma_entries if not entry.get("instance")]
        if not dmaauto.controllers(model):
            notes.append("this device has no DMA request definitions; skipping DMA auto-allocation")
        elif wanted:
            requests = []
            for entry in wanted:
                request = entry.get("request")
                if request and request not in requests:
                    requests.append(request)
            candidates = _dma_candidates(model, target, requests)
            assignment, conflicts = dmaauto.solve(requests, candidates)
            if assignment is None:
                raise AllocationError(
                    "these DMA requests cannot be placed together (see conflicts: candidates and occupants)",
                    "allocation.dma", conflicts)
            for request in requests:
                chosen = assignment[request]
                for entry in wanted:
                    if entry.get("request") != request:
                        continue
                    entry["instance"] = chosen["instance"]
                    detail = "controller %s" % chosen["controller"]
                    if chosen.get("channel"):
                        detail += ", channel %s" % chosen["channel"]
                    notes.append("DMA request %s auto-selected %s (%s)"
                                 % (request, chosen["instance"], detail))

    result = dict(target)
    result["pins"] = pin_entries
    return result, notes